#pragma once

#ifndef ESP8266BASE_USE_WEB
#define ESP8266BASE_USE_WEB 1
#endif

#ifndef ESP8266BASE_USE_OTA
#define ESP8266BASE_USE_OTA 0
#endif

// 持久化能力分层。Filesystem 只负责挂载 LittleFS；Config 和 FileLog 是
// 独立的上层能力。没有持久化需求的终端可以让三者全部不进入 ELF。
#ifndef ESP8266BASE_USE_FILESYSTEM
#define ESP8266BASE_USE_FILESYSTEM 1
#endif

#ifndef ESP8266BASE_CFG_FORMAT_ON_FAIL
#define ESP8266BASE_CFG_FORMAT_ON_FAIL 0
#endif

#ifndef ESP8266BASE_USE_CONFIG
#define ESP8266BASE_USE_CONFIG ESP8266BASE_USE_FILESYSTEM
#endif

#ifndef ESP8266BASE_USE_WIFI_CONFIG
#define ESP8266BASE_USE_WIFI_CONFIG ESP8266BASE_USE_CONFIG
#endif

#ifndef ESP8266BASE_USE_WEB_AUTH_CONFIG
#define ESP8266BASE_USE_WEB_AUTH_CONFIG ESP8266BASE_USE_CONFIG
#endif

#ifndef ESP8266BASE_USE_FILELOG
#define ESP8266BASE_USE_FILELOG (!ESP8266BASE_PROFILE_MQTT_TERMINAL && ESP8266BASE_USE_CONFIG)
#endif

// 正式 MQTT 智能终端运行模式：统一轻量 HTTP、OTA 与 MQTT/TLS 生命周期。
#ifndef ESP8266BASE_PROFILE_MQTT_TERMINAL
#define ESP8266BASE_PROFILE_MQTT_TERMINAL 0
#endif

// MQTT_TERMINAL 在 STA/重连状态下的根路径跳转目标。业务可以在构建期
// 指向自己的只读状态页；AP 配网仍始终跳转 /wifi。
#ifndef ESP8266BASE_TERMINAL_HOME_PATH
#define ESP8266BASE_TERMINAL_HOME_PATH "/health"
#endif

#if ESP8266BASE_PROFILE_MQTT_TERMINAL != 0 && ESP8266BASE_PROFILE_MQTT_TERMINAL != 1
#error "ESP8266BASE_PROFILE_MQTT_TERMINAL must be 0 or 1"
#endif

#ifndef ESP8266BASE_USE_MQTT
#define ESP8266BASE_USE_MQTT ESP8266BASE_PROFILE_MQTT_TERMINAL
#endif

#if ESP8266BASE_USE_MQTT != 0 && ESP8266BASE_USE_MQTT != 1
#error "ESP8266BASE_USE_MQTT must be 0 or 1"
#endif

#if ESP8266BASE_USE_FILESYSTEM != 0 && ESP8266BASE_USE_FILESYSTEM != 1
#error "ESP8266BASE_USE_FILESYSTEM must be 0 or 1"
#endif
#if ESP8266BASE_USE_CONFIG != 0 && ESP8266BASE_USE_CONFIG != 1
#error "ESP8266BASE_USE_CONFIG must be 0 or 1"
#endif
#if ESP8266BASE_USE_FILELOG != 0 && ESP8266BASE_USE_FILELOG != 1
#error "ESP8266BASE_USE_FILELOG must be 0 or 1"
#endif
#if ESP8266BASE_USE_WIFI_CONFIG != 0 && ESP8266BASE_USE_WIFI_CONFIG != 1
#error "ESP8266BASE_USE_WIFI_CONFIG must be 0 or 1"
#endif
#if ESP8266BASE_USE_WEB_AUTH_CONFIG != 0 && ESP8266BASE_USE_WEB_AUTH_CONFIG != 1
#error "ESP8266BASE_USE_WEB_AUTH_CONFIG must be 0 or 1"
#endif
#if ESP8266BASE_USE_CONFIG && !ESP8266BASE_USE_FILESYSTEM
#error "ESP8266BASE_USE_CONFIG requires ESP8266BASE_USE_FILESYSTEM=1"
#endif
#if ESP8266BASE_USE_FILELOG && !ESP8266BASE_USE_CONFIG
#error "ESP8266BASE_USE_FILELOG requires ESP8266BASE_USE_CONFIG=1"
#endif
#if ESP8266BASE_USE_WIFI_CONFIG && !ESP8266BASE_USE_CONFIG
#error "ESP8266BASE_USE_WIFI_CONFIG requires ESP8266BASE_USE_CONFIG=1"
#endif
#if ESP8266BASE_USE_WEB_AUTH_CONFIG && !ESP8266BASE_USE_CONFIG
#error "ESP8266BASE_USE_WEB_AUTH_CONFIG requires ESP8266BASE_USE_CONFIG=1"
#endif

#ifndef ESP8266BASE_DEFAULT_HOSTNAME
#define ESP8266BASE_DEFAULT_HOSTNAME "esp8266base"
#endif

#ifndef ESP8266BASE_USE_NTP
#define ESP8266BASE_USE_NTP 0
#endif

#ifndef ESP8266BASE_USE_MDNS
#define ESP8266BASE_USE_MDNS 1
#endif

#ifndef ESP8266BASE_USE_SLEEP
#define ESP8266BASE_USE_SLEEP 1
#endif

#ifndef ESP8266BASE_USE_WATCHDOG
#define ESP8266BASE_USE_WATCHDOG 1
#endif

#if ESP8266BASE_USE_OTA && !ESP8266BASE_USE_WEB
#error "ESP8266BASE_USE_OTA requires ESP8266BASE_USE_WEB=1"
#endif
#if ESP8266BASE_USE_WEB && !ESP8266BASE_PROFILE_MQTT_TERMINAL && !ESP8266BASE_USE_CONFIG
#error "full management Web requires ESP8266BASE_USE_CONFIG=1; use MQTT_TERMINAL for configless minimal Web"
#endif
#if ESP8266BASE_USE_MQTT && !ESP8266BASE_USE_NTP
#error "ESP8266BASE_USE_MQTT requires ESP8266BASE_USE_NTP=1 for TLS time validation"
#endif

#if ESP8266BASE_PROFILE_MQTT_TERMINAL && !ESP8266BASE_USE_WEB
#error "ESP8266BASE_PROFILE_MQTT_TERMINAL requires ESP8266BASE_USE_WEB=1"
#endif
#if ESP8266BASE_PROFILE_MQTT_TERMINAL && !ESP8266BASE_USE_OTA
#error "ESP8266BASE_PROFILE_MQTT_TERMINAL requires ESP8266BASE_USE_OTA=1"
#endif
#if ESP8266BASE_PROFILE_MQTT_TERMINAL && !ESP8266BASE_USE_NTP
#error "ESP8266BASE_PROFILE_MQTT_TERMINAL requires ESP8266BASE_USE_NTP=1"
#endif
#if ESP8266BASE_PROFILE_MQTT_TERMINAL && !ESP8266BASE_USE_WATCHDOG
#error "ESP8266BASE_PROFILE_MQTT_TERMINAL requires ESP8266BASE_USE_WATCHDOG=1"
#endif
#if ESP8266BASE_PROFILE_MQTT_TERMINAL && !ESP8266BASE_USE_MQTT
#error "ESP8266BASE_PROFILE_MQTT_TERMINAL requires ESP8266BASE_USE_MQTT=1"
#endif
